  <h2>Frequently asked</h2>

  <h3>How do I sync between my phone and computer?</h3>
  <p>Sign in with the same account on each device. Changes appear everywhere instantly.</p>

  <h3>How do I share a project?</h3>
  <p>Open the project, tap Share, and invite people by email. They need a TooDue account with that address.</p>

  <h3>How do I connect Google Calendar?</h3>
  <p>Open Settings and tap Connect Google Calendar. Dated tasks show up on a dedicated TooDue calendar.</p>

  <h3>I forgot my password.</h3>
  <p>Email <a href="mailto:support@toodue.com">support@toodue.com</a> from the address on your account and we'll help you get back in.</p>

  <h3>How do I delete my account?</h3>
  <p>
    In the app, open <strong>Settings → Delete account</strong>, enter your password and confirm. Your account and all of
    its data are permanently deleted right away. See the <a href="/privacy">privacy policy</a> for details.
  </p>

  <h3>Can I export or self-host my data?</h3>
  <p>Yes. TooDue is open source; see <a href="https://github.com/djedi/toodue">the repository</a> for self-hosting.</p>
